import {
  AppWindow,
  BookOpen,
  Box,
  Clapperboard,
  Columns2,
  File,
  FileText,
  Files,
  Folder,
  GalleryHorizontal,
  Image,
  Images,
  LayoutGrid,
  LetterH,
  Link,
  List,
  ListOrdered,
  Mail,
  Map,
  MapPin,
  Menu,
  MousePointerClick,
  Newspaper,
  Palette,
  Quote,
  Rows3,
  ScrollText,
  Settings2,
  Sparkles,
  Table,
  Tag,
  TextAlignStart,
  Users,
  Video,
  type LucideProps,
} from "lucide-react";

type IconComponent = React.ComponentType<LucideProps>;

/**
 * Icons available by name in config (`icon: "book-open"`). A curated set
 * keeps the control panel bundle small; unknown names fall back to a file.
 */
const ICONS: Record<string, IconComponent> = {
  "app-window": AppWindow,
  "book-open": BookOpen,
  box: Box,
  clapperboard: Clapperboard,
  "columns-2": Columns2,
  file: File,
  "file-text": FileText,
  files: Files,
  folder: Folder,
  "gallery-horizontal": GalleryHorizontal,
  image: Image,
  images: Images,
  "layout-grid": LayoutGrid,
  "letter-h": LetterH,
  link: Link,
  list: List,
  "list-ordered": ListOrdered,
  mail: Mail,
  map: Map,
  "map-pin": MapPin,
  menu: Menu,
  "mouse-pointer-click": MousePointerClick,
  newspaper: Newspaper,
  palette: Palette,
  quote: Quote,
  "rows-3": Rows3,
  "scroll-text": ScrollText,
  "settings-2": Settings2,
  sparkles: Sparkles,
  table: Table,
  tag: Tag,
  "text-align-start": TextAlignStart,
  users: Users,
  video: Video,
};

export function Icon({ name, ...props }: { name?: string } & LucideProps) {
  const Cmp = (name && ICONS[name]) || File;
  return <Cmp strokeWidth={1.9} {...props} />;
}
